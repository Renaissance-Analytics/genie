import { APP_BRIDGE, KIND_SPECS, type ElementDefinition, type FieldSpec } from './catalog.js';
import { ungrantable } from './gapp-grants.js';

/**
 * THE APP-SDK'S TYPES, GENERATED FROM THE CATALOG (GApps v2, V6, Tynn #571), as B7 generates docs/sdk: the bridge, the `app`
 * element's payload, and the arguments of every element an app can be granted. `npm run docs:sdk` writes them to
 * packages/app-sdk/src/generated.ts and test/app-sdk.test.ts is the drift check, so they cannot differ from what the host
 * enforces. A terminal id is an agent's and never authorable, so it is left out.
 */
interface Schema { type?: string; enum?: unknown[]; items?: Schema; properties?: Record<string, Schema>; required?: string[] }

const NEVER_AUTHORABLE = new Set(['terminalId']);
const literal = (value: unknown): string => (typeof value === 'string' ? `'${value.replace(/['\\]/g, (c) => `\\${c}`)}'` : JSON.stringify(value));
const keyOf = (name: string): string => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : literal(name));

function typeOf(schema: Schema, indent: string): string {
    if (Array.isArray(schema.enum) && schema.enum.length > 0) return schema.enum.map(literal).join(' | ');
    switch (schema.type) {
        case 'string': return 'string';
        case 'number': case 'integer': return 'number';
        case 'boolean': return 'boolean';
        case 'array': {
            const item = schema.items ? typeOf(schema.items, indent) : 'unknown';
            return item.includes(' | ') ? `(${item})[]` : `${item}[]`;
        }
        case 'object': return schema.properties ? objectOf(schema, indent) : 'Record<string, unknown>';
        default: return 'unknown';
    }
}

function objectOf(schema: Schema, indent: string): string {
    const required = new Set(schema.required ?? []);
    const entries = Object.entries(schema.properties ?? {}).filter(([name]) => !NEVER_AUTHORABLE.has(name));
    if (entries.length === 0) return 'Record<string, never>';
    const inner = `${indent}    `;
    return `{\n${entries.map(([name, prop]) => `${inner}${keyOf(name)}${required.has(name) ? '' : '?'}: ${typeOf(prop, inner)};`).join('\n')}\n${indent}}`;
}

function fieldType(field: FieldSpec): string {
    if (field.tsType) return field.tsType;
    switch (field.rule) {
        case 'packagePath': return 'string';
        case 'elementIds': return 'string[]';
        case 'oneOf': return (field.options ?? []).map(literal).join(' | ');
        case 'object': return 'Record<string, unknown>';
        default: return 'unknown';
    }
}

export function renderAppSdkTypes(definitions: readonly ElementDefinition[]): string {
    const app = KIND_SPECS.find((spec) => spec.kind === 'app')!;
    const elements = definitions.filter((d) => d.kind === 'tool' && ungrantable(d) === null);
    return [
        '// Generated by `npm run docs:sdk` from Genie\'s catalog (src/core/sdk-types.ts). Do not edit: change the catalog and run it again.',
        '',
        `export const BRIDGE_CALLS = [${APP_BRIDGE.calls.map(literal).join(', ')}] as const;`,
        `export const BRIDGE_EVENTS = [${APP_BRIDGE.events.map(literal).join(', ')}] as const;`,
        '',
        '/** The payload of an `app` element in genie-package.json. */',
        'export interface AppElementPayload {',
        ...app.fields.map((field) => `    ${field.name}${field.required ? '' : '?'}: ${fieldType(field)};`),
        '}',
        '',
        '/** Genie\'s own elements an app can be granted, and each one\'s arguments. */',
        'export interface GenieElements {',
        ...elements.map((d) => `    ${keyOf(d.id)}: ${objectOf(d.payload.inputSchema as Schema, '    ')};`),
        '}',
        '',
    ].join('\n');
}
